// The PWA: shells/web as static files in shells/web/dist (installable, offline after the first visit).
// A small plugin writes sw.js with the list of built files, so the service worker needs no tooling.
import { createHash } from 'node:crypto';
import { defineConfig } from 'vite';
import type { Plugin } from 'vite';
import { svelte, vitePreprocess } from '@sveltejs/vite-plugin-svelte';

function serviceWorker(): Plugin {
  return {
    name: 'zensudoku-sw',
    apply: 'build',
    generateBundle(_, bundle) {
      const files = Object.keys(bundle).filter(f => f !== 'sw.js');
      // public/ files (manifest, icons) are copied after this hook, so list them by name.
      const extra = ['manifest.webmanifest', 'icon.svg', 'icon-192.png', 'icon-512.png'];
      const urls = ['./', ...files, ...extra];
      const version = createHash('sha256').update(files.map(f => (bundle[f] as { fileName: string }).fileName).join('|')).digest('hex').slice(0, 10);
      this.emitFile({
        type: 'asset', fileName: 'sw.js',
        source: `// Generated by vite.pwa.config.ts. Cache-first for the app's own files; a new build replaces the old cache.
const CACHE = 'zensudoku-${version}';
const URLS = ${JSON.stringify(urls)};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(URLS)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req).catch(() => req.mode === 'navigate' ? caches.match('./') : Response.error())));
});
`,
      });
    },
  };
}

export default defineConfig({
  root: 'shells/web',
  base: './',
  plugins: [svelte({ preprocess: vitePreprocess() }), serviceWorker()],
  publicDir: 'public',
  build: { outDir: 'dist', emptyOutDir: true, target: 'es2022', sourcemap: false },
  server: { host: '127.0.0.1' },
});
